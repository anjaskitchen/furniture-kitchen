/**
 * Generate supabase/seed.sql dari lib/demo-data.ts
 * Jalankan: npm run seed:sql
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import * as d from "../lib/demo-data.ts";

type Row = Record<string, unknown>;

function lit(v: unknown): string {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return `array[${v.map(lit).join(", ")}]::text[]`.replace("array[]::text[]", "'{}'::text[]");
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
}

function insert(table: string, rows: Row[], omit: string[] = []): string {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]).filter((c) => !omit.includes(c));
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n");
  const quoted = cols.map((c) => (c === "group" ? '"group"' : c));
  return `insert into public.${table} (${quoted.join(", ")}) values\n${values}\non conflict do nothing;\n\n`;
}

let sql = `-- Seed data awal (generated by scripts/generate-seed.ts — jangan edit manual)\n-- Dijalankan sekali oleh npm run db:seed setelah migrasi (supabase/migrations).
-- Aman dijalankan ulang (on conflict do nothing).\n\n`;
sql += insert("settings", [{ id: true, ...d.demoSettings }]);
sql += insert("categories", d.demoCategories as unknown as Row[]);
sql += insert("materials", d.demoMaterials as unknown as Row[]);
sql += insert("products", d.demoProducts as unknown as Row[]);
sql += insert("hpl_colors", d.demoHplColors as unknown as Row[]);
sql += insert("duco_colors", d.demoDucoColors as unknown as Row[]);
sql += insert("hardware", d.demoHardware as unknown as Row[]);
sql += insert("price_settings", d.demoPriceSettings as unknown as Row[]);
sql += insert("portfolio", d.demoPortfolio as unknown as Row[]);
sql += insert("videos", d.demoVideos as unknown as Row[]);
sql += insert("reviews", d.demoReviews as unknown as Row[]);
sql += insert("home_sections", d.demoHomeSections as unknown as Row[]);
sql += insert("features", d.demoFeatures as unknown as Row[]);
sql += insert("faqs", d.demoFaqs as unknown as Row[]);

writeFileSync(join(import.meta.dirname, "..", "supabase", "seed.sql"), sql);
console.log("supabase/seed.sql written");
